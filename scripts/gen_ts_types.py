#!/usr/bin/env python3
"""Generate web/src/protocol/types.ts from the vrcas_protocol models (spec §5.8).

    python scripts/gen_ts_types.py            # write the file
    python scripts/gen_ts_types.py --check    # exit 1 if it's stale (tests/test_protocol.py does this too)
    python scripts/gen_ts_types.py --schema protocol-schema.json   # also dump the JSON Schema

The models are exported as JSON Schema (pydantic) and each definition becomes a TypeScript type.
The envelope and the type → payload map are written from the MODELS catalogue.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "protocol"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from vrcas_protocol import MODELS  # noqa: E402
from vrcas_protocol.envelope import ROLES  # noqa: E402

OUT = ROOT / "web" / "src" / "protocol" / "types.ts"

HEADER = """\
// Generated by scripts/gen_ts_types.py from protocol/vrcas_protocol. Do not edit by hand:
// change the pydantic models and run `python scripts/gen_ts_types.py`.

/* eslint-disable */
"""


def schema() -> dict:
    models = sorted({m for m in MODELS.values() if m is not None}, key=lambda m: m.__name__)
    _, combined = models_json_schema([(m, "validation") for m in models], ref_template="#/$defs/{model}")
    return combined


def ts_type(node: dict) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    if "anyOf" in node:
        parts: list[str] = []
        for option in node["anyOf"]:
            part = ts_type(option)
            if part not in parts:
                parts.append(part)
        return " | ".join(parts)
    kind = node.get("type")
    if kind == "array":
        inner = ts_type(node.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object":
        if node.get("properties"):
            raise ValueError("inline object types aren't supported; use a model")
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def comment(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    lines = [line.strip() for line in text.strip().splitlines()]
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}".rstrip() for line in lines), f"{indent} */"]


def definition(name: str, node: dict) -> list[str]:
    out = comment(node.get("description"))
    props = node.get("properties", {})
    if not props:
        return out + [f"export type {name} = Record<string, never>;"]
    required = set(node.get("required", []))
    out.append(f"export interface {name} {{")
    for prop, spec in props.items():
        out += comment(spec.get("description"), "  ")
        optional = "" if prop in required else "?"
        out.append(f"  {prop}{optional}: {ts_type(spec)};")
    out.append("}")
    return out


def render() -> str:
    defs = schema()["$defs"]
    lines = [HEADER]
    lines.append(f"export type Role = {' | '.join(json.dumps(r) for r in ROLES)};")
    lines.append("")
    for name in sorted(defs):
        lines += definition(name, defs[name])
        lines.append("")
    lines.append("/** Payload (`data`) of each message type. Types without a model aren't read by the relay. */")
    lines.append("export interface MessageData {")
    for type_, model in MODELS.items():
        lines.append(f"  {json.dumps(type_)}: {model.__name__ if model else 'Record<string, unknown>'};")
    lines.append("}")
    lines.append("")
    lines.append("export type MsgType = keyof MessageData;")
    lines.append("")
    lines.append("/** \"server\": handled by the relay. \"all\": every approved session except the sender. */")
    lines.append('export type Target = "server" | "all" | { role: Role } | { ids: string[] };')
    lines.append("")
    lines += comment("""The v2 envelope (spec §5.1). The relay sets `from` (a session id, or "server").
`ts` is the sender's server-synced time in ms; `reply_to` is the id of the message this answers.""")
    lines.append("export interface Envelope<T extends MsgType = MsgType> {")
    lines.append("  v: 2;")
    lines.append("  /** ULID, unique per message */")
    lines.append("  id: string;")
    lines.append("  type: T;")
    lines.append("  from: string | null;")
    lines.append("  to: Target;")
    lines.append("  ts: number | null;")
    lines.append("  reply_to: string | null;")
    lines.append("  data: MessageData[T];")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    parser.add_argument("--schema", type=Path, help="also write the JSON Schema here")
    args = parser.parse_args(argv)
    if args.schema:
        args.schema.write_text(json.dumps(schema(), indent=2) + "\n", encoding="utf-8")
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if args.check:
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale. Run: python scripts/gen_ts_types.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
